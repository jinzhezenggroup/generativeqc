"""Generate the explicit qualified stationary CUDA AOT package inventory."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from tools.generate_native_semilocal_families import load_manifest

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "manifests/stationary_aot_profiles.json"
OUTPUT = (
    ROOT / "python/generativeqc_compiler/method/_generated_stationary_aot_profiles.py"
)
SCHEMA = "generativeqc.stationary-aot-build-profiles.v1"


def load_profiles() -> tuple[tuple[str, int, str, bool], ...]:
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if data.get("schema") != SCHEMA:
        raise ValueError("invalid stationary CUDA AOT profile schema")
    codes = {row["symbol"]: row["code"] for row in load_manifest()}
    result: list[tuple[str, int, str, bool]] = []
    names: set[str] = set()
    legacy_codes: set[int] = set()
    for record in data["profiles"]:
        if set(record) != {"name", "family", "method", "legacy"}:
            raise ValueError("invalid stationary CUDA AOT profile")
        name, family, method, legacy = (
            record["name"],
            record["family"],
            record["method"],
            record["legacy"],
        )
        if (
            not isinstance(name, str)
            or not name
            or name in names
            or not isinstance(method, str)
            or not method
            or family not in codes
            or type(legacy) is not bool
        ):
            raise ValueError("invalid or duplicated stationary CUDA AOT profile")
        names.add(name)
        code = codes[family]
        if legacy:
            if code in legacy_codes:
                raise ValueError("ambiguous legacy stationary CUDA AOT transport")
            legacy_codes.add(code)
        result.append((name, code, method, legacy))
    if not result or not legacy_codes:
        raise ValueError("empty stationary CUDA AOT inventory")
    return tuple(result)


def emit_python() -> str:
    lines = [
        '"""Generated stationary CUDA AOT package inventory. Do not edit."""',
        "",
        "# Generated by tools/generate_stationary_aot_profiles.py from",
        "# manifests/stationary_aot_profiles.json.",
        "",
        "STATIONARY_AOT_BUILD_PROFILES = (",
    ]
    lines.extend(
        f"    ({json.dumps(name)}, {code}, {json.dumps(method)}, {legacy}),"
        for name, code, method, legacy in load_profiles()
    )
    return "\n".join((*lines, ")", ""))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = emit_python()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != output:
            raise SystemExit("stale generated stationary CUDA AOT profiles")
    else:
        OUTPUT.write_text(output, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
