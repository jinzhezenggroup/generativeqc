"""Project MethodSpec recipes into immutable, generic XC execution registrations.

Method policy stays here; the XC compiler consumes only rational component sums
and a separately bound full-range exchange fraction. Existing native providers
remain preferred whenever their complete semantic contract matches.
"""

from __future__ import annotations

import argparse
import pprint
import sys
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "python"), str(ROOT)]

from generativeqc_compiler.common.provenance import canonical_hash
from generativeqc_compiler.method.spec import METHOD_CATALOG
from generativeqc_compiler.xc.libxc_bulk_capabilities import available_capabilities
from generativeqc_compiler.xc.spec import POINTWISE_BULK_COMPONENTS

OUTPUT = ROOT / "python/generativeqc_compiler/xc/_generated_semilocal_compositions.py"
HEADER = ROOT / "src/dft/generated_semilocal_compositions.hpp"


def registrations() -> dict:
    """Deduplicate electronic recipes without admitting corrections or RSH."""
    supported = {
        item.name
        for item in available_capabilities()
        if item.name in POINTWISE_BULK_COMPONENTS
        and set(item.required_ingredients) <= {"rho", "sigma", "tau"}
    }
    result = {}
    codes = {}
    for name, spec in sorted(METHOD_CATALOG.items()):
        if (
            spec.range_omega
            or spec.nonlocal_correlation
            or spec.dispersion
            or spec.basis
            or spec.gcp
        ):
            continue
        terms = {}
        for component, coefficient in spec.semilocal_components:
            terms[component] = terms.get(component, Fraction(0)) + coefficient
        components = tuple(
            sorted((key, str(value)) for key, value in terms.items() if value)
        )
        if not components or any(
            key not in supported or Fraction(value) < 0 for key, value in components
        ):
            continue
        if len(components) == 1 and components[0][1] == "1" and not spec.exact_exchange:
            continue
        payload = {"components": components, "exact_exchange": str(spec.exact_exchange)}
        identity = canonical_hash(payload)
        code = 0x40000000 | int(identity[:7], 16)
        if code in codes and codes[code] != identity:
            raise ValueError(
                "composed XC code collision; revise the encoding explicitly"
            )
        codes[code] = identity
        key = f"COMPOSED_{identity[:16].upper()}"
        if key not in result:
            result[key] = {**payload, "code": code, "methods": []}
        result[key]["methods"].append(name)
    return dict(sorted(result.items()))


def render() -> str:
    """Emit typed immutable recipe data without importing the method compiler."""
    return (
        '"""Generated rational XC compositions; run tools/generate_semilocal_compositions.py."""\n\n'
        + "from typing import TypedDict\n\n\nclass CompositionRecord(TypedDict):\n"
        + '    """Serialized recipe and its deterministic native registration."""\n\n'
        + "    components: tuple[tuple[str, str], ...]\n    exact_exchange: str\n"
        + "    code: int\n    methods: list[str]\n\n\n"
        + "# fmt: off\nCOMPOSITIONS: dict[str, CompositionRecord] = "
        + pprint.pformat(registrations(), sort_dicts=True, width=88)
        + "\n"
    )


def render_header() -> str:
    """Keep native exchange metadata independent of point-program linkage."""
    cases = "\n".join(
        f"    case {record['code']}U:\n      return {float(Fraction(record['exact_exchange'])).hex()};"
        for record in registrations().values()
        if Fraction(record["exact_exchange"])
    )
    return f"""// Generated by tools/generate_semilocal_compositions.py; do not edit.
#pragma once
#include <cstdint>

namespace generativeqc::dft::generated {{
// This describes XC/EXX science, independently of installed CPU/CUDA artifacts.
constexpr double automatic_libxc_exact_exchange(std::uint32_t code) noexcept {{
  switch (code) {{
{cases}
    default:
      return 0.0;
  }}
}}
}}  // namespace generativeqc::dft::generated
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, source in ((OUTPUT, render()), (HEADER, render_header())):
        if args.check:
            if path.read_text() != source:
                raise SystemExit(f"stale semilocal composition registry: {path}")
        else:
            path.write_text(source)


if __name__ == "__main__":
    main()
