def cpu_header() -> typing.Any:
    lines = [
        "// Generated by tools/generate_mp2_native.py from generativeqc_compiler.mp2; equations are TensorIR.",
        "#pragma once",
        "#include <algorithm>",
        "#include <cmath>",
        "#include <cstddef>",
        "#include <stdexcept>",
        "#include <vector>",
        "namespace generativeqc::mp2::generated {",
        "using CpuRun = void(*)(const double*,const double*,double,double,const double*,const double*,double*);",
        "struct CpuPlan { CpuRun run; std::size_t numeric_bytes; const char* equation_hash; };",
    ]
    plans = []
    for tile in (1, 2, 4, 8):
        program = prepare_for_backend(
            energy_program((1, 1, tile, tile)),
            "cpu",
        )
        lines.append(emit_cpu(program, function_name=f"tile_{tile}"))
        feeds = {"g": "g", "x": "x", "ei": "&ei", "ej": "&ej", "ea": "ea", "eb": "eb"}
        inputs = ",".join(
            feeds[n.attrs["name"]] for n in program.live_nodes if n.op == "input"
        )
        lines.append(
            f"inline void run_{tile}(const double* g,const double* x,double ei,double ej,const double* ea,const double* eb,double* out) {{ const double* inputs[]={{{inputs}}}; double* outputs[]={{out,out+1}}; tile_{tile}(inputs,outputs); }}"
        )
        plans.append(
            f'case {tile}: return {{run_{tile},{cpu_capacity(program)}ULL,"{program.logical_hash}"}};'
        )
    lines.append(
        "inline CpuPlan cpu_plan(unsigned tile) { switch(tile) {"
        + "".join(plans)
        + 'default: throw std::invalid_argument("unsupported MP2 tile"); }}'
    )
    lines.append("}")
    return "\n".join(lines) + "\n"


def ump2_density_program(channel: str) -> tuple[Program, Fraction]:
    """Polarize epsilon bars from the existing spin energy's common VJP/JVP.

    The retained physical integral bar includes both same-spin exchange
    scatters. At unit g, x=-g and denominator -1, its slope is bar_g-bar_x
    (bar_g for opposite spin). Deriving that normalization from the VJP keeps
    the energy owner authoritative; no spin prefactor is restated here.
    """
    import numpy as np

    primal = unrestricted_energy_program(
        (1, 1, 1, 1), channel=channel, differentiable=True
    )
    reverse = transpose_program(primal, ("energy",)).program
    unit = {
        "g": 1.0,
        "x": -1.0,
        "ei": -1.0,
        "ej": 0.0,
        "ea": 0.0,
        "eb": 0.0,
        "bar_energy": 1.0,
    }
    values = execute(
        reverse,
        {
            node.attrs["name"]: np.full(node.spec.shape, unit[node.attrs["name"]])
            for node in reverse.live_nodes
            if node.op == "input"
        },
    ).outputs
    slope = float(values["bar_g"].item())
    if "bar_x" in values:
        slope -= float(values["bar_x"].item())
    if not np.isfinite(slope) or slope == 0:
        raise ValueError("invalid UMP2 physical integral-bar normalization")
    normalization = Fraction(slope)
    tangent = ("g", "x") if channel != "alpha_beta" else ("g",)
    forward = linearize(
        reverse, tangent, outputs=("bar_ei", "bar_ej", "bar_ea", "bar_eb")
    ).program
    # For the quadratic epsilon cotangent Q, B(u,v)=DQ(u)[v]/2.
    bilinear = Program(
        {
            name: add(node, coefficients=(Fraction(1, 2),))
            for name, node in forward.outputs.items()
        },
        provenance={
            "source_energy": primal.logical_hash,
            "source_reverse": reverse.logical_hash,
            "source_jvp": forward.logical_hash,
            "physical_bar_normalization": str(normalization),
        },
    )
    return prepare_for_backend(bilinear, "cpu"), normalization


def ump2_cpu_header() -> str:
    """Lower the established spin-labelled UMP2 TensorIR to scalar CPU tiles."""
    lines = [
        "// Generated by tools/generate_mp2_native.py from compiler UMP2 TensorIR; do not edit.",
        "#pragma once",
        "#include <algorithm>",
        "#include <cmath>",
        "#include <cstddef>",
        "#include <stdexcept>",
        "#include <vector>",
        '#include "tensor/cpu_runtime.hpp"',
        "namespace generativeqc::mp2::generated {",
        "using Ump2Run = void(*)(double,double,double,double,double,double,double*);",
        "struct Ump2CpuPlan { Ump2Run run; std::size_t numeric_bytes; const char* equation_hash; };",
    ]
    plans = []
    hashes = []
    for channel in ("alpha_alpha", "beta_beta", "alpha_beta"):
        program = prepare_for_backend(
            unrestricted_energy_program((1, 1, 1, 1), channel=channel), "cpu"
        )
        hashes.append(program.logical_hash)
        lines.append(emit_cpu(program, function_name=f"ump2_tile_{channel}"))
        feeds = {name: f"&{name}" for name in ("g", "x", "ei", "ej", "ea", "eb")}
        inputs = ",".join(
            feeds[node.attrs["name"]]
            for node in program.live_nodes
            if node.op == "input"
        )
        lines.append(
            f"inline void ump2_run_{channel}(double g,double x,double ei,double ej,double ea,double eb,double* out) "
            f"{{ const double* inputs[]={{{inputs}}}; double* outputs[]={{out}}; "
            f"ump2_tile_{channel}(inputs,outputs); }}"
        )
        plans.append(
            f"case {len(plans)}: return {{ump2_run_{channel},{cpu_capacity(program)}ULL,"
            f'"{program.logical_hash}"}};'
        )
    lines.append(
        "inline Ump2CpuPlan ump2_cpu_plan(unsigned channel) { switch(channel) {"
        + "".join(plans)
        + 'default: throw std::invalid_argument("unknown UMP2 spin channel"); }}'
    )
    # The reverse is emitted by the same TensorIR owner as the energy.
    adjoint_plans = []
    order = ("g", "x", "ei", "ej", "ea", "eb")
    for channel in ("alpha_alpha", "beta_beta", "alpha_beta"):
        primal = unrestricted_energy_program(
            (1, 1, 1, 1), channel=channel, differentiable=True
        )
        reverse = prepare_for_backend(
            transpose_program(primal, ("energy",)).program, "cpu"
        )
        source, resources = emit_bounded_cpu(reverse, symbol=f"ump2_reverse_{channel}")
        source = source.replace('#include "cpu_runtime.hpp"', "").replace(
            'extern "C" int', "inline int"
        )
        lines.extend((f"namespace reverse_{channel} {{", source, "}"))
        feeds = {name: name for name in order}
        feeds["bar_energy"] = "seed"
        inputs = ",".join(
            feeds[node.attrs["name"]]
            for node in reverse.live_nodes
            if node.op == "input"
        )
        copies = " ".join(
            f"out[{order.index(name.removeprefix('bar_'))}]=bars[{k}];"
            for k, name in enumerate(reverse.outputs)
        )
        lines.append(
            f"inline void ump2_adjoint_{channel}(double g,double x,double ei,double ej,double ea,double eb,double* out) "
            f"{{ const double seed=1.0; std::fill_n(out,6,0.0); const double inputs[]={{{inputs}}}; "
            f"double bars[{resources['output_count']}]; "
            f"if(reverse_{channel}::ump2_reverse_{channel}(inputs,{resources['input_count']},bars,{resources['output_count']},{resources['required_bytes']}ULL)) "
            f'throw std::runtime_error("nonfinite UMP2 adjoint"); {copies} }}'
        )
        adjoint_plans.append(
            f"case {len(adjoint_plans)}: return {{ump2_adjoint_{channel},{resources['required_bytes']}ULL,"
            f'"{reverse.logical_hash}"}};'
        )
    lines.append(
        "inline Ump2CpuPlan ump2_adjoint_cpu_plan(unsigned channel) { switch(channel) {"
        + "".join(adjoint_plans)
        + 'default: throw std::invalid_argument("unknown UMP2 adjoint channel"); }}'
    )
    # Finite same-space Fock weights use the existing physical ijab bars.
    lines.extend(
        (
            "using Ump2DensityRun = void(*)(double,double,double*);",
            "struct Ump2DensityCpuPlan { Ump2DensityRun run; std::size_t numeric_bytes; const char* equation_hash; };",
        )
    )
    density_plans = []
    for channel in ("alpha_alpha", "beta_beta", "alpha_beta"):
        bilinear, normalization = ump2_density_program(channel)
        source, resources = emit_bounded_cpu(
            bilinear, symbol=f"ump2_density_tile_{channel}"
        )
        source = source.replace('#include "cpu_runtime.hpp"', "").replace(
            'extern "C" int', "inline int"
        )
        lines.extend((f"namespace density_{channel} {{", source, "}"))
        scale = float(normalization).hex()
        feeds = {
            "g": f"left/({scale})",
            "x": f"-left/({scale})",
            "d_g": f"right/({scale})",
            "d_x": f"-right/({scale})",
            "ei": "-1.0",
            "ej": "0.0",
            "ea": "0.0",
            "eb": "0.0",
            "bar_energy": "1.0",
        }
        inputs = ",".join(
            feeds[node.attrs["name"]]
            for node in bilinear.live_nodes
            if node.op == "input"
        )
        copies = " ".join(
            f"out[{('ei', 'ej', 'ea', 'eb').index(name.removeprefix('d_bar_'))}]=bars[{k}];"
            for k, name in enumerate(bilinear.outputs)
        )
        lines.append(
            f"inline void ump2_density_{channel}(double left,double right,double* out) "
            f"{{ const double inputs[]={{{inputs}}}; double bars[4]; "
            f"if(density_{channel}::ump2_density_tile_{channel}(inputs,{resources['input_count']},bars,4,{resources['required_bytes']}ULL)) "
            f'throw std::runtime_error("nonfinite UMP2 density adjoint"); {copies} }}'
        )
        density_plans.append(
            f"case {len(density_plans)}: return {{ump2_density_{channel},{resources['required_bytes']}ULL,"
            f'"{bilinear.logical_hash}"}};'
        )
    lines.append(
        "inline Ump2DensityCpuPlan ump2_density_cpu_plan(unsigned channel) { switch(channel) {"
        + "".join(density_plans)
        + 'default: throw std::invalid_argument("unknown UMP2 density channel"); }}'
    )
    inventory = hashlib.sha256("\n".join(hashes).encode("ascii")).hexdigest()
    lines.append(f'inline constexpr char kUmp2InventoryHash[] = "{inventory}";')
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cpu-header", type=Path)
    parser.add_argument("--ump2-cpu-header", type=Path)
    parser.add_argument("--cuda-dir", type=Path)
    parser.add_argument("--architectures", default="90")
    args = parser.parse_args()
    if args.cpu_header:
        args.cpu_header.parent.mkdir(parents=True, exist_ok=True)
        args.cpu_header.write_text(cpu_header(), encoding="utf-8")
        args.cpu_header.with_name("block_capacity_generated.hpp").write_text(
            block_capacity_header(), encoding="utf-8"
        )
        args.cpu_header.with_name("mp2_schedule_generated.hpp").write_text(
            mp2_schedule_header(), encoding="utf-8"
        )
        args.cpu_header.with_name("source_reuse_schedule_generated.hpp").write_text(
            source_reuse_header(), encoding="utf-8"
        )
    if args.ump2_cpu_header:
        args.ump2_cpu_header.parent.mkdir(parents=True, exist_ok=True)
        args.ump2_cpu_header.write_text(ump2_cpu_header(), encoding="utf-8")
    if args.cuda_dir:
        cuda_sources(args.cuda_dir, args.architectures)
    if not args.cpu_header and not args.ump2_cpu_header and not args.cuda_dir:
        parser.error("select a CPU header and/or --cuda-dir")


def _numeric_architectures(value: typing.Any) -> typing.Any:
    raw = [item.strip() for item in value.split(";") if item.strip()]
    special = {"native", "all", "all-major"}
    unsupported = sorted({item.lower() for item in raw if item.lower() in special})
    if unsupported:
        values = ", ".join(unsupported)
        raise ValueError(
            "MP2 CUDA generation requires numeric architectures; "
            f"CMake special value(s) {values} are unsupported. "
            "Configure with values such as 75;90."
        )
    try:
        result = sorted({int(item.split("-")[0]) for item in raw})
    except ValueError as exc:
        raise ValueError(
            "MP2 CUDA generation requires numeric architectures such as 75;90."
        ) from exc
    if not result:
        raise ValueError(
            "MP2 CUDA generation requires at least one numeric architecture."
        )
    return result


def cuda_sources(directory: typing.Any, architectures: typing.Any) -> None:
    from generativeqc_compiler.common.cuda_target import cuda_target_info
    from generativeqc_compiler.tensor.cuda_emit import emit_cuda
    from generativeqc_compiler.tensor.cuda_plan import plan_cuda
    from generativeqc_compiler.tensor.scalar_cpp import emit_scalar_cpp

    archs = _numeric_architectures(architectures)
    directory.mkdir(parents=True, exist_ok=True)
    pair_program = pair_energy_program()
    pair_source = emit_scalar_cpp(
        pair_program,
        function_name="ri_mp2_pair_energy",
        input_order=("g", "x", "ei", "ej", "ea", "eb"),
        output_order=("opposite_spin", "same_spin"),
        caller_owned_checks=True,
        ordered_native_sums=True,
        output_dependency_order=True,
    ).replace(
        "inline bool ri_mp2_pair_energy",
        "__device__ __forceinline__ bool ri_mp2_pair_energy",
        1,
    )
    (directory / "mp2_pair_energy.cuh").write_text(
        "// Generated by tools/generate_mp2_native.py from generativeqc_compiler.mp2; do not edit.\n"
        "#pragma once\n"
        "#include <cmath>\n"
        "namespace generativeqc::mp2::generated {\n"
        f"// TensorIR logical hash: {pair_program.logical_hash}\n"
        + pair_source
        + "}  // namespace generativeqc::mp2::generated\n",
        encoding="utf-8",
    )
    table = [
        '#include "posthf/mp2_cuda_plan.hpp"',
        "#include <cuda_runtime.h>",
        "#include <stdexcept>",
        "namespace generativeqc::mp2::generated {",
    ]
    choices = []
    for arch in archs:
        for tile in (1, 2, 4, 8):
            program = prepare_for_backend(
                energy_program((1, 1, tile, tile)),
                "cuda",
            )
            plan = plan_cuda(
                program,
                cuda_target_info(f"sm_{arch}"),
                max_bytes=1 << 20,
                reassociate_contractions=False,
            )
            prefix = f"mp2_sm{arch}_t{tile}_"
            source = emit_cuda(plan, symbol_prefix=prefix)
            feeds = {
                "g": "g",
                "x": "x",
                "ei": "&ei",
                "ej": "&ej",
                "ea": "ea",
                "eb": "eb",
            }
            inputs = ",".join(
                feeds[plan.steps[k].node.attrs["name"]] for k in plan.inputs
            )
            source += f"""\nextern "C" int {prefix}run(void* p,const double* g,const double* x,double ei,double ej,const double* ea,const double* eb,double* out,generativeqc_tensor::Metrics* metrics,char* error,size_t size) {{
const void* inputs[]={{{inputs}}}; void* outputs[]={{out,out+1}};
return {prefix}generated::{prefix}tensor_run(p,inputs,outputs,1,metrics,error,size);
}}\n"""
            (directory / f"{prefix}runtime.cu").write_text(source, encoding="utf-8")
            table += [
                f'extern "C" int {prefix}tensor_create(int,void**,char*,std::size_t);',
                f'extern "C" void {prefix}tensor_destroy(void*);',
                f'extern "C" int {prefix}run(void*,const double*,const double*,double,double,const double*,const double*,double*,generativeqc_tensor::Metrics*,char*,std::size_t);',
            ]
            choices.append(
                f'''if (arch=={arch} && tile=={tile}) return {{{prefix}tensor_create,{prefix}tensor_destroy,{prefix}run,{plan.peak_bytes}ULL,{plan.allocation_bytes}ULL,"{program.logical_hash}"}};'''
            )
    table += [
        'CudaPlan cuda_plan(unsigned tile,int device) { cudaDeviceProp p{}; if (cudaGetDeviceProperties(&p,device)!=cudaSuccess) throw std::runtime_error("CUDA MP2 device probe failed"); const int arch=10*p.major+p.minor;',
        *choices,
        'throw std::runtime_error("MP2 tensor plan is not compiled for this architecture/tile");',
        "}",
        "}",
    ]
    (directory / "mp2_cuda_table.cu").write_text(
        "\n".join(table) + "\n", encoding="utf-8"
    )


if __name__ == "__main__":
    main()
