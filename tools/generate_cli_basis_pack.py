"""Generate the shared Python-free native basis catalog from the bundled BSE subset."""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path


def _number(value: object, *, positive: bool, label: str) -> str:
    if not isinstance(value, (str, int, float)) or isinstance(value, bool):
        raise TypeError(f"{label} must be a decimal scalar")
    text = str(value)
    number = float(text)
    if not math.isfinite(number) or (positive and number <= 0.0):
        raise ValueError(f"invalid {label}: {value!r}")
    return text


def load_pack(
    path: Path,
) -> list[tuple[str, list[tuple[int, int, list[tuple[str, str]]]]]]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if payload.get("schema_version") != 1 or not isinstance(payload.get("bases"), dict):
        raise ValueError("unsupported bundled basis-pack schema")

    result = []
    for name, basis in sorted(payload["bases"].items()):
        if not isinstance(name, str) or not name or name != name.lower():
            raise ValueError("basis names must be non-empty lowercase strings")
        elements = basis.get("elements") if isinstance(basis, dict) else None
        if not isinstance(elements, dict) or not elements:
            raise ValueError(f"{name}: basis requires element records")
        rows = []
        for atomic_text, shells in sorted(
            elements.items(), key=lambda item: int(item[0])
        ):
            atomic_number = int(atomic_text)
            if (
                not 1 <= atomic_number <= 118
                or not isinstance(shells, list)
                or not shells
            ):
                raise ValueError(f"{name}: invalid element record {atomic_text!r}")
            for shell in shells:
                if not isinstance(shell, dict):
                    raise TypeError(f"{name}: shell must be an object")
                angular = shell.get("angular_momentum")
                exponents = shell.get("exponents")
                coefficients = shell.get("coefficients")
                if (
                    not isinstance(angular, int)
                    or isinstance(angular, bool)
                    or angular < 0
                    or not isinstance(exponents, list)
                    or not isinstance(coefficients, list)
                    or not exponents
                    or len(exponents) != len(coefficients)
                ):
                    raise ValueError(f"{name}: malformed shell for Z={atomic_number}")
                primitives = [
                    (
                        _number(exponent, positive=True, label="basis exponent"),
                        _number(coefficient, positive=False, label="basis coefficient"),
                    )
                    for exponent, coefficient in zip(
                        exponents, coefficients, strict=True
                    )
                ]
                rows.append((atomic_number, angular, primitives))
        result.append((name, rows))
    return result


def emit(
    pack: list[tuple[str, list[tuple[int, int, list[tuple[str, str]]]]]],
    source_sha256: str,
) -> str:
    primitives: list[tuple[str, str]] = []
    shells: list[tuple[int, int, int]] = []
    elements: list[tuple[int, int, int]] = []
    bases: list[tuple[str, int, int, int, int, int, int]] = []

    for name, rows in pack:
        shell_offset = len(shells)
        primitive_offset = len(primitives)
        element_offset = len(elements)
        current_element = None
        for atomic_number, angular, shell_primitives in rows:
            if atomic_number != current_element:
                if current_element is not None:
                    element_start = elements[-1][1]
                    elements[-1] = (
                        current_element,
                        element_start,
                        len(shells) - shell_offset - element_start,
                    )
                current_element = atomic_number
                elements.append((atomic_number, len(shells) - shell_offset, 0))
            shells.append(
                (angular, len(primitives) - primitive_offset, len(shell_primitives))
            )
            primitives.extend(shell_primitives)
        element_start = elements[-1][1]
        elements[-1] = (
            current_element,
            element_start,
            len(shells) - shell_offset - element_start,
        )
        bases.append(
            (
                name,
                element_offset,
                len(elements) - element_offset,
                shell_offset,
                len(shells) - shell_offset,
                primitive_offset,
                len(primitives) - primitive_offset,
            )
        )

    lines = [
        "// Generated by tools/generate_cli_basis_pack.py from python/generativeqc/data/basis_pack.json.",
        "// Shared SDK/CLI templates; installed execution reads no JSON and imports no Python.",
        "#ifndef GENERATIVEQC_NATIVE_BASIS_PACK_HPP",
        "#define GENERATIVEQC_NATIVE_BASIS_PACK_HPP",
        "",
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        '#include "generativeqc/generativeqc.h"',
        "",
        "namespace generativeqc::molecule::basis_generated {",
        "",
        f'inline constexpr char kSourceSha256[] = "{source_sha256}";',
        "",
        "struct BasisRow {",
        "  std::string_view name;",
        "  std::uint32_t element_offset, element_count;",
        "  std::uint32_t shell_offset, shell_count;",
        "  std::uint32_t primitive_offset, primitive_count;",
        "};",
        "",
        f"inline constexpr std::array<double, {len(primitives)}> kExponents{{{{",
    ]
    lines.extend(f"    {exponent}," for exponent, coefficient in primitives)
    lines.extend(
        [
            "}};",
            "",
            f"inline constexpr std::array<double, {len(primitives)}> kCoefficients{{{{",
        ]
    )
    lines.extend(f"    {coefficient}," for exponent, coefficient in primitives)
    lines.extend(
        [
            "}};",
            "",
            f"inline constexpr std::array<generativeqc_basis_shell_template_v1, {len(shells)}> kShells{{{{",
        ]
    )
    lines.extend(
        f"    {{{angular}u, {offset}u, {count}u, {offset}u, 1u}},"
        for angular, offset, count in shells
    )
    lines.extend(
        [
            "}};",
            "",
            f"inline constexpr std::array<generativeqc_basis_element_template_v1, {len(elements)}> kElements{{{{",
        ]
    )
    lines.extend(
        f"    {{{atomic_number}, 0, {offset}u, {count}u, 0, 0}},"
        for atomic_number, offset, count in elements
    )
    lines.extend(
        ["}};", "", f"inline constexpr std::array<BasisRow, {len(bases)}> kBases{{{{"]
    )
    lines.extend(
        f'    {{"{name}", {element_offset}u, {element_count}u, {shell_offset}u, {shell_count}u, {primitive_offset}u, {primitive_count}u}},'
        for name, element_offset, element_count, shell_offset, shell_count, primitive_offset, primitive_count in bases
    )
    lines.extend(
        [
            "}};",
            "",
            "}  // namespace generativeqc::molecule::basis_generated",
            "",
            "#endif",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    payload = json.loads(args.input.read_text(encoding="utf-8"))
    source_sha256 = hashlib.sha256(
        json.dumps(
            payload, sort_keys=True, separators=(",", ":"), allow_nan=False
        ).encode()
    ).hexdigest()
    text = emit(load_pack(args.input), source_sha256)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text(encoding="utf-8") != text:
        args.output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
