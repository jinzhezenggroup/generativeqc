"""Emit runtime-shape native UCCSD and four canonical triples channels.

Mathematics comes exclusively from the shared unrestricted TensorIR inventory.
Only emission/storage are shared with RCCSD; unrestricted amplitudes and spin
populations are never replaced by their restricted counterparts. Python runs at
build time, not from the public method execution owner.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if __package__ in (None, ""):
    sys.path.insert(0, str(ROOT))
    sys.path.insert(0, str(ROOT / "python"))

from generativeqc_compiler.cc.uccsd_equations import build_program
from generativeqc_compiler.cc.uccsd_layout import UCCSDLayout
from generativeqc_compiler.cc.uccsd_triples import CHANNELS, build_tile_program
from generativeqc_compiler.common.evidence import canonical_hash
from generativeqc_compiler.tensor import Program, prepare_for_backend

from tools.generate_rccsd_native import (
    _cpu_function,
    _dim,
    _execution_nodes,
    _label_dims,
    _required_function,
    _scaled_bilinear_cpp,
)

DIMENSIONS = ("oa", "ob", "va", "vb")
PARAMETERS = ",".join(f"std::size_t {name}" for name in DIMENSIONS)


def _prepared(program: Program) -> Program:
    """Keep the audited reduction order and shared lifetime-aware arena plan."""
    prepared = prepare_for_backend(program, "cpu", preserve_reduction_order=True)
    return Program(
        prepared.outputs,
        provenance={**prepared.provenance, "native_execution_order": "dependencies"},
    )


def _work(
    program: Program, name: str, *, dimensions: tuple[str, ...] = DIMENSIONS
) -> str:
    """Publish checked scalar summands for complete-endpoint work admission."""
    parameters = ",".join(f"std::size_t {dimension}" for dimension in dimensions)
    lines = [f"inline std::size_t {name}({parameters}){{", "std::size_t work=0;"]
    for node in _execution_nodes(program):
        if node.op == "einsum":
            extents = ",".join(_label_dims(node).values()) or "1"
            lines.append(f"work=checked_add(work,checked_product({{{extents}}}));")
    return "\n".join([*lines, "return work;}"])


def cpu_header() -> str:
    """Generate shape metadata, physical residual replay and singleton tiles."""
    primal = build_program(3, 3, 3, 3)
    program = _prepared(primal)
    inputs = {
        node.attrs["name"]: node.spec
        for node in program.live_nodes
        if node.op == "input"
    }
    names = sorted(inputs)
    outputs = tuple(program.outputs)
    lines = [
        "// Generated by tools/generate_uccsd_native.py; do not edit.",
        "#pragma once",
        "#include <algorithm>",
        "#include <array>",
        "#include <cmath>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <initializer_list>",
        "#include <limits>",
        "#include <stdexcept>",
        "namespace generativeqc::cc::ucc_generated {",
        'inline std::size_t checked_add(std::size_t left,std::size_t right){if(right>std::numeric_limits<std::size_t>::max()-left)throw std::length_error("UCC size overflow");return left+right;}',
        'inline std::size_t checked_product(std::initializer_list<std::size_t> values){std::size_t result=1;for(auto value:values){if(value&&result>std::numeric_limits<std::size_t>::max()/value)throw std::length_error("UCC size overflow");result*=value;}return result;}',
        _scaled_bilinear_cpp(),
        f'inline constexpr char kEquationHash[]="{primal.logical_hash}";',
        "struct Inputs {",
        *(f"const double* {name}{{}};" for name in names),
        "};",
        "struct Outputs {",
        *(f"const double* {name}{{}};" for name in outputs),
        "};",
        "struct FeedSpec { const char* name; std::array<unsigned,4> axes; unsigned rank; const double* Inputs::* field; };",
        f"inline constexpr std::array<FeedSpec,{len(names)}> kFeeds{{{{",
    ]
    for name in names:
        axes = [DIMENSIONS.index(_dim(index)) for index in inputs[name].indices]
        padded = ",".join(str(axis) for axis in [*axes, *([0] * (4 - len(axes)))])
        lines.append(f'{{"{name}",{{{padded}}},{len(axes)},&Inputs::{name}}},')
    lines += [
        "}};",
        _required_function(program, "required", dimension_names=DIMENSIONS),
        _work(program, "work"),
        _cpu_function(
            program,
            "evaluate",
            "Outputs",
            output_fields=outputs,
            dimension_names=DIMENSIONS,
            input_overrides={name: f"inputs.{name}" for name in names},
        ),
    ]
    tile_hashes = []
    for channel in CHANNELS:
        tile_dimensions = (*DIMENSIONS, "tile_extent")
        tile = build_tile_program(UCCSDLayout(3, 3, 3, 3), channel, (1,) * 6)
        tile_hashes.append(tile.program.logical_hash)
        program = _prepared(tile.program)
        names = sorted(operand.name for operand in tile.operands)
        lines += [
            f"struct Inputs_{channel} {{",
            *(f"const double* {name}{{}};" for name in names),
            "};",
            "struct TriplesOutput { const double* triples_energy; };"
            if channel == CHANNELS[0]
            else "",
            f"struct Binding_{channel} {{ const char* source; const char* labels; std::array<unsigned,4> axes; unsigned rank; const double* Inputs_{channel}::* field; }};",
            f"inline constexpr std::array<Binding_{channel},{len(tile.operands)}> kBindings_{channel}{{{{",
        ]
        for operand in tile.operands:
            padded = ",".join(
                str(axis) for axis in [*operand.axes, *([0] * (4 - len(operand.axes)))]
            )
            lines.append(
                f'{{"{operand.source}","{operand.labels}",{{{padded}}},{len(operand.axes)},&Inputs_{channel}::{operand.name}}},'
            )
        lines += [
            "}};",
            _required_function(
                program, f"required_{channel}", dimension_names=tile_dimensions
            ),
            _work(program, f"work_{channel}", dimensions=tile_dimensions),
            _cpu_function(
                program,
                f"evaluate_{channel}",
                "TriplesOutput",
                signature=f"const Inputs_{channel}& inputs",
                output_fields=("triples_energy",),
                dimension_names=tile_dimensions,
                input_overrides={name: f"inputs.{name}" for name in names},
            ),
        ]
    lines += [
        f'inline constexpr char kTriplesHash[]="{canonical_hash(tile_hashes)}";',
        "}  // namespace generativeqc::cc::ucc_generated",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    """Write deterministic source for the native CMake owner."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cpu-header", type=Path, required=True)
    arguments = parser.parse_args()
    arguments.cpu_header.parent.mkdir(parents=True, exist_ok=True)
    arguments.cpu_header.write_text(cpu_header())


if __name__ == "__main__":
    main()
