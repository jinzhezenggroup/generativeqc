"""Build-only physical-owner matrix schedule of canonical ERI factors.

The fourth mathematical center defines the fixed origin. Constant physical-owner
incidence is applied to existing factor partials before product composition,
avoiding unused independent-center derivatives. Scalar factors and coordinate
responses retain their existing owners. Distinct owners are never inferred from
numeric coordinate equality. The all-distinct nine-coordinate operation remains
an explicit case of this operation, not an approximation or separate algebra.
Every ordered mixed derivative is generated by the incumbent scalar Graph/AD.
No post-evaluation matrix symmetrization is performed.
"""

