"""Bounded forward/reverse lowering of canonical scalar integral expression graphs.

Each scalar rule and its directional derivative is generated by Graph AD once.
A primitive's immutable instruction stream retains only its value graph, rather
than expanding one gradient/HVP expression per input. The native interpreter
owns traversal and scratch; all mathematical operation rules remain generated.
"""

from __future__ import annotations

import math
from typing import TYPE_CHECKING

from .expr import Graph, Node
from .scalar_c import ScalarCEmitter

if TYPE_CHECKING:
    from .parameter_ad import ParameterKernel


def operation_key(node: Node) -> tuple[str, float | None]:
    """Distinguish fixed-power primitives while preserving exact operand order."""
    if node.operation != "power":
        return node.operation, None
    if node.payload is None:
        raise ValueError("power node is missing its exponent")
    return node.operation, float(node.payload)


def emit_tape_support(
    kernels: tuple[ParameterKernel, ...], *, second_order: bool = True
) -> tuple[str, dict, int]:
    """Emit generated scalar rules and report maximum per-primitive tape capacity."""
    from .parameter_ad import ParameterKernel, _emit_kernel

    keys = set()
    maximum = 0
    for kernel in kernels:
        roots = (
            (kernel.value,)
            if kernel.boys_argument is None
            else (kernel.boys_argument, kernel.value)
        )
        nodes = tuple(
            kernel.graph.nodes[i] for i in kernel.graph.topological_order(roots)
        )
        maximum = max(maximum, sum(max(1, len(node.arguments) - 1) for node in nodes))
        keys.update(
            operation_key(node)
            for node in nodes
            if node.operation not in ("constant", "variable")
        )
    codes = {key: i + 3 for i, key in enumerate(sorted(keys, key=str))}
    lines = [
        "struct TapeInstruction { int opcode, left, right; double parameter; };",
        f"constexpr int parameter_tape_nodes={maximum};",
    ]
    for (operation, power), code in codes.items():
        graph = Graph()
        left, right = graph.variable("left"), graph.variable("right")
        if operation == "add":
            value = left + right
        elif operation == "multiply":
            value = left * right
        elif operation == "reciprocal":
            value = graph.reciprocal(left)
        elif operation == "exp":
            value = graph.exponential(left)
        elif operation == "power":
            assert power is not None
            value = left.pow(power)
        else:
            raise ValueError(f"unsupported integral tape operation {operation}")
        kernel = ParameterKernel(
            graph,
            value,
            ("left", "right"),
            (graph.differentiate(value, left), graph.differentiate(value, right)),
            None,
            0,
        )
        lines.append(
            _emit_kernel(f"tape_rule_{code}", kernel, second_order=second_order)
        )
    lines.append(
        "template<class Scalar> static void tape_rule(int code, const Scalar* x, Scalar* out) { switch(code) {"
    )
    lines.extend(
        f"case {code}: tape_rule_{code}(x,out,true); return;" for code in codes.values()
    )
    lines.append("default: out[0]=NAN; return; }}")
    lines.append("static double primal_value(double x) { return x; }")
    if second_order:
        lines.append("static double primal_value(Directional x) { return x.value; }")
    # Boys is an external analytic leaf, not a differentiated recurrence. The
    # three neighboring moments supply its value, derivative and derivative JVP.
    graph = Graph()
    f0, f1, f2, d = (graph.variable(name) for name in ("f0", "f1", "f2", "direction"))
    variables = {
        "f0": "boys[order]",
        "f1": "boys[order+1]",
        "f2": "boys[order+2]",
        "direction": "argument.tangent",
    }
    emitter = ScalarCEmitter(graph, variables)
    roots = (f0, -f1 * d, -f1, f2 * d)
    emitter.emit(roots)
    if second_order:
        lines.extend(
            (
                "static void tape_boys(Directional argument, const double* boys, int order, Directional* out) {",
                *emitter.lines,
                f"out[0]={{{emitter.reference(roots[0])},{emitter.reference(roots[1])}}};",
                f"out[1]={{{emitter.reference(roots[2])},{emitter.reference(roots[3])}}};",
                "}",
            )
        )
    emitter = ScalarCEmitter(graph, variables)
    emitter.emit((f0, -f1))
    lines.extend(
        (
            "static void tape_boys(double, const double* boys, int order, double* out) {",
            *emitter.lines,
            f"out[0]={emitter.reference(f0)}; out[1]={emitter.reference(-f1)};",
            "}",
        )
    )
    return "\n".join(lines), codes, maximum


def emit_tape_kernel(
    name: str, kernel: ParameterKernel, codes: dict, *, second_order: bool = True
) -> str:
    """Serialize one value graph, reconnecting Boys leaves to their argument."""
    roots = (
        (kernel.value,)
        if kernel.boys_argument is None
        else (kernel.boys_argument, kernel.value)
    )
    order = tuple(kernel.graph.topological_order(roots))
    indices: dict[int, int] = {}
    records = []
    for identifier in order:
        node = kernel.graph.nodes[identifier]
        if node.operation == "constant":
            assert node.payload is not None
            record = (0, 0, 0, float(node.payload))
        elif node.operation == "variable":
            name_in = str(node.payload)
            if name_in == "kPi":
                record = (0, 0, 0, math.pi)
            elif name_in.startswith("boys_"):
                assert kernel.boys_argument is not None
                record = (
                    2,
                    int(name_in.removeprefix("boys_")),
                    indices[kernel.boys_argument.identifier],
                    0,
                )
            else:
                record = (1, kernel.parameters.index(name_in), 0, 0)
        else:
            if len(node.arguments) > 2 and node.operation not in ("add", "multiply"):
                raise ValueError("unsupported n-ary integral tape operation")
            left = indices[node.arguments[0]]
            code = codes[operation_key(node)]
            # Match C-family left association of n-ary arithmetic exactly.
            for argument in node.arguments[1:-1]:
                records.append("{" + f"{code},{left},{indices[argument]},0" + "}")
                left = len(records) - 1
            right = indices[node.arguments[-1]] if len(node.arguments) > 1 else left
            record = (code, left, right, 0)
        indices[identifier] = len(records)
        records.append("{" + ",".join(format(value, ".17g") for value in record) + "}")
    boys = (
        (kernel.boys_count - int(not second_order))
        if kernel.boys_argument is not None
        else 0
    )
    return (
        f"static const TapeInstruction {name}_tape[]={{\n"
        + ",\n".join(records)
        + "\n};\n"
        f"template<class Scalar> static void {name}(const Scalar* x, Scalar* out, bool derivative, Scalar* scratch) {{\n"
        f"evaluate_tape<{boys}>({name}_tape,{len(records)},{len(kernel.parameters)},{indices[kernel.value.identifier]},x,out,derivative,scratch);\n}}"
    )
