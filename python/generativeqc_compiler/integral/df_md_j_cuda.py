"""Three-center Hermite contractions for a proposed native DF J consumer.

The orbital-pair and auxiliary densities are already in Hermite form. This
lowering shares the Direct compiler's radial recurrence and state inventory;
it owns no basis normalization, screening, allocation, metric solve or runtime
admission. Emission alone does not register or qualify a production backend.
"""

from __future__ import annotations

from .md_j_engine_cuda import _hermite_states, emit_md_radial_function

MAXIMUM_PAIR_ANGULAR = 7
MAXIMUM_AUXILIARY_ANGULAR = 5


def emit_df_md_j_header() -> str:
    """Emit FP64 forward/transpose contractions through orbital f and auxiliary g.

    One first response raises either side, reaching order eleven (364 radial
    entries). The rectangular address inventory also contains the unused (7,5)
    corner, which is rejected by the contraction guard. Addresses use
    uint16 rather than the Direct s/p/d consumer's uint8 inventory. The two
    products are exact transposes of the same signed Coulomb matrix; pair
    symmetry factors and primitive prefactors remain the caller's responsibility.
    """
    mappings: list[int] = []
    signs: list[int] = []
    for auxiliary in range(MAXIMUM_AUXILIARY_ANGULAR + 1):
        signs.extend(-1 if sum(s) & 1 else 1 for s in _hermite_states(auxiliary))
    for pair in range(MAXIMUM_PAIR_ANGULAR + 1):
        for auxiliary in range(MAXIMUM_AUXILIARY_ANGULAR + 1):
            radial = {
                state: index
                for index, state in enumerate(_hermite_states(pair + auxiliary))
            }
            mappings.extend(
                radial[tuple(a + b for a, b in zip(first, second, strict=True))]
                for first in _hermite_states(pair)
                for second in _hermite_states(auxiliary)
            )
    if max(mappings) >= 1 << 16:
        raise ValueError("DF Hermite address inventory exceeds uint16")
    indices = ",\n".join(
        "    " + ", ".join(map(str, mappings[begin : begin + 24]))
        for begin in range(0, len(mappings), 24)
    )
    tables = f"""// Divergent component lanes use read-only global address tables.
static __device__ const std::uint16_t kDfMdAddresses[{len(mappings)}] = {{
{indices}
}};
static __device__ __constant__ const signed char kDfMdAuxiliarySigns[{len(signs)}] = {{
    {", ".join(map(str, signs))}
}};
"""
    return (
        _PREAMBLE + emit_md_radial_function(11, "df_md_radial") + tables + _CONTRACTIONS
    )


