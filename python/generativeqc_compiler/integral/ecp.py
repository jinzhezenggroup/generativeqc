"""ECP operator IR and generated Gaussian center-derivative quadrature kernels."""

import typing
from dataclasses import replace

from .blocks import RawBlock, TensorLayout, WeightDescriptor, WeightedDerivative
from .expr import Graph
from .ir import (
    ECP_MAX_ORBITAL_ANGULAR,
    EcpCenter,
    OperatorSpec,
    TranslationInvariant,
    build_integral_ir,
)
from .scalar_c import ScalarCEmitter
from .shell_signature import BasisShell, CenterBinding, ShellSignature
from .shell_spec import cartesian_components


def build_ecp_ir(
    angular: typing.Any,
    terms: typing.Any,
    *,
    derivatives: typing.Any = False,
    weighted: typing.Any = False,
) -> typing.Any:
    """Preserve A/B/C and generic weighted semantics before atom mapping."""
    if len(angular) != 2:
        raise ValueError("ECP requires two orbital shell slots")
    signature = ShellSignature(
        tuple(BasisShell(i, i, momentum) for i, momentum in enumerate(angular)),
        tuple(CenterBinding(i) for i in range(3)),
    )
    operator = OperatorSpec(
        "scalar_ecp",
        (0, 1, 2),
        (TranslationInvariant(),),
        (EcpCenter(2, tuple(terms)),),
        ((0, 1), (1, 0)),
    )
    matrix = TensorLayout(signature.tensor_indices, signature.component_shape)
    integral = build_integral_ir(
        signature,
        operator=operator,
        contractions=(RawBlock(matrix, matrix.storage_bytes),),
        recurrence="ecp_quadrature",
    )
    if weighted and not derivatives:
        raise ValueError("weighted ECP contractions require derivatives")
    if not derivatives:
        return integral
    layout = TensorLayout(("center", "xyz"), (3, 3))
    if weighted:
        consumer = WeightedDerivative(
            WeightDescriptor("ecp_weight", matrix), layout, layout.storage_bytes
        )
    else:
        layout = TensorLayout(
            layout.indices + matrix.indices, layout.shape + matrix.shape
        )
        consumer = RawBlock(layout, layout.storage_bytes)
    return replace(
        integral, derivative=operator.nuclear_derivative(), contractions=(consumer,)
    )


def gaussian_roots(component: typing.Any, *, order: int = 1) -> typing.Any:
    """Differentiate AO centers symbolically before emitting device arithmetic."""
    if order not in (1, 2):
        raise ValueError("ECP AO derivative order must be one or two")
    graph = Graph()
    xyz = [graph.variable(a) for a in "xyz"]
    alpha = graph.variable("alpha")
    value = graph.exponential(-alpha * graph.sum(x * x for x in xyz))
    for axis, coordinate in zip("xyz", xyz, strict=True):
        for _ in range(component.count(axis)):
            value = value * coordinate
    gradient = tuple(-graph.differentiate(value, coordinate) for coordinate in xyz)
    second = (
        tuple(
            -graph.differentiate(gradient[first], xyz[second])
            for first in range(3)
            for second in range(first, 3)
        )
        if order == 2
        else ()
    )
    return graph, (value, *gradient, *second)


def emit_ecp_ao_cuda() -> typing.Any:
    """Specialize all validated Cartesian components; no runtime AD."""
    lines = [
        "#pragma once",
        "#include <cmath>",
        "// Generated by tools/generate_ecp_kernels.py.",
        "namespace generativeqc::generated {",
        f"inline constexpr unsigned ecp_max_orbital_angular = {ECP_MAX_ORBITAL_ANGULAR};",
    ]
    for order, name, width in ((1, "ecp_ao", 4), (2, "ecp_ao_second", 10)):
        lines.extend(_emit_ao_function(order, name, width))
    return "\n".join(lines + ["}", ""])


def _emit_ao_function(order: int, name: str, width: int) -> list[str]:
    lines = [
        f"__device__ inline void {name}(unsigned lx,unsigned ly,unsigned lz,",
        "    double x,double y,double z,double alpha,double* out) {",
        "  if (lx>ecp_max_orbital_angular || ly>ecp_max_orbital_angular ||",
        "      lz>ecp_max_orbital_angular || lx+ly+lz>ecp_max_orbital_angular) {",
        f"    for(int i=0;i<{width};++i) out[i]=NAN;",
        "    return;",
        "  }",
        "  switch (16*lx+4*ly+lz) {",
    ]
    for angular in range(ECP_MAX_ORBITAL_ANGULAR + 1):
        for component in cartesian_components(angular):
            graph, roots = gaussian_roots(component, order=order)
            emitter = ScalarCEmitter(graph, {})
            emitter.emit(roots)
            key = (
                16 * component.count("x")
                + 4 * component.count("y")
                + component.count("z")
            )
            lines += [
                f"case {key}: {{",
                *emitter.lines,
                *(
                    f"out[{i}]={emitter.reference(root)};"
                    for i, root in enumerate(roots)
                ),
                "return; }",
            ]
    return lines + ["}", f"for(int i=0;i<{width};++i) out[i]=NAN;", "}"]
