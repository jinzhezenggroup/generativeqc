"""Compiler-owned coupled KS response maps around an external induced Fock.

The runtime owns state authentication, spin coupling, and the linear solve. All
orbital/density/energy-weighted-density algebra lives here; D and W tangents are
generated by TensorIR AD, including the full occupied energy-matrix tangent.
"""

from __future__ import annotations

from fractions import Fraction

from generativeqc_compiler.tensor.ad_program import _rebuild, linearize
from generativeqc_compiler.tensor.ir import (
    Node,
    add,
    broadcast,
    einsum,
    input_tensor,
    multiply,
)
from generativeqc_compiler.tensor.program import Program
from generativeqc_compiler.tensor.types import Index, IndexSpace, TensorSpec


def build_ks_cpks_maps(
    nao: int = 3, occupied: int = 1, *, occupation: int = 1
) -> dict[str, Program]:
    """Build dimension witnesses for one spin, not an uncoupled spin solve.

    AO, full-orbital, occupied and virtual populations have distinct identities
    even when witness sizes coincide. Zero-size occupied/virtual populations
    are legal. ``occupation`` is two for RKS and one for each UKS spin block.
    The native owner must submit all spin densities to one induced-Fock action.
    """
    if (
        type(nao) is not int
        or type(occupied) is not int
        or nao < 1
        or not 0 <= occupied <= nao
        or type(occupation) is not int
        or occupation not in (1, 2)
    ):
        raise ValueError("invalid KS CPKS witness or occupation")
    spaces = {
        "ao": IndexSpace("cpks_ao", "ao", nao),
        "orbital": IndexSpace("cpks_orbital", "orbital", nao),
        "occupied": IndexSpace("cpks_occupied", "occupied", occupied),
        "virtual": IndexSpace("cpks_virtual", "virtual", nao - occupied),
    }

    def tensor(name: str, *domains: str) -> Node:
        return input_tensor(
            name,
            TensorSpec(
                tuple(
                    Index(f"axis_{axis}", spaces[domain])
                    for axis, domain in enumerate(domains)
                ),
                role="parameter",
                differentiable=True,
            ),
        )

    coefficients = tensor("coefficients", "ao", "orbital")
    co = tensor("occupied", "ao", "occupied")
    cv = tensor("virtuals", "ao", "virtual")
    eo = tensor("occupied_energies", "occupied")
    ev = tensor("virtual_energies", "virtual")
    rotation = tensor("rotation", "occupied", "virtual")
    overlap = tensor("overlap_direction", "ao", "ao")
    frozen = tensor("frozen_fock", "ao", "ao")
    induced = tensor("induced_fock", "ao", "ao")
    metric_motion = tensor("metric_motion", "ao", "occupied")
    orbital_motion = tensor("orbital_motion", "ao", "occupied")
    occupied_energy = tensor("occupied_energy_matrix", "occupied", "occupied")

    density = Program({"density": einsum("ui,vi->uv", co, co, coefficient=occupation)})
    density_jvp = linearize(density, ("occupied",)).program

    def density_motion(motion: Node) -> Program:
        tangent = next(
            node
            for node in density_jvp.nodes
            if node.op == "input" and node.attrs["name"] == "d_occupied"
        )
        return _rebuild(density_jvp, {tangent: motion})

    metric = einsum(
        "up,pi->ui",
        coefficients,
        einsum("up,ui->pi", coefficients, einsum("uv,vi->ui", overlap, co)),
        coefficient=Fraction(-1, 2),
    )
    rotating = einsum("ua,ia->ui", cv, rotation)
    moving = add(metric_motion, rotating)
    gap = add(
        broadcast(ev, rotation.spec.indices, (1,)),
        broadcast(eo, rotation.spec.indices, (0,)),
        coefficients=(1, -1),
    )
    energy_sum = add(
        broadcast(ev, rotation.spec.indices, (1,)),
        broadcast(eo, rotation.spec.indices, (0,)),
    )

    def ov(matrix: Node) -> Node:
        return einsum("ui,ua->ia", co, einsum("uv,va->ua", matrix, cv))

    total_fock = add(frozen, induced)
    occupied_fock = einsum("ui,uj->ij", co, einsum("uv,vj->uj", total_fock, co))
    occupied_overlap = einsum("ui,uj->ij", co, einsum("uv,vj->uj", overlap, co))
    occupied_sum = add(
        broadcast(eo, occupied_fock.spec.indices, (0,)),
        broadcast(eo, occupied_fock.spec.indices, (1,)),
    )
    energy_motion = add(
        occupied_fock,
        multiply(occupied_overlap, occupied_sum),
        coefficients=(1, Fraction(-1, 2)),
    )
    weights = Program(
        {
            "weights": einsum(
                "ui,vi->uv",
                einsum("uj,ji->ui", co, occupied_energy),
                co,
                coefficient=occupation,
            )
        }
    )
    weights_jvp = linearize(weights, ("occupied", "occupied_energy_matrix")).program
    replacements = {
        node: orbital_motion if node.attrs["name"] == "d_occupied" else energy_motion
        for node in weights_jvp.nodes
        if node.op == "input" and node.attrs["name"].startswith("d_")
    }
    weights_motion = _rebuild(weights_jvp, replacements)
    metric_density = density_motion(metric)
    final_density = density_motion(moving)
    return {
        "metric": Program(
            {
                "gap": gap,
                "metric_motion": metric,
                "density": metric_density.outputs["d_density"],
            },
            definitions=metric_density.definitions,
        ),
        "rotation": density_motion(rotating),
        "action": Program({"action": add(multiply(gap, rotation), ov(induced))}),
        "rhs": Program(
            {
                "rhs": add(
                    ov(total_fock),
                    multiply(ov(overlap), energy_sum),
                    coefficients=(-1, Fraction(1, 2)),
                )
            }
        ),
        "density": Program(
            {"orbital_motion": moving, "density": final_density.outputs["d_density"]},
            definitions=final_density.definitions,
        ),
        "weights": weights_motion,
    }
