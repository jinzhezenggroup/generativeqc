"""One scalar Coulomb energy authority for host/device nuclear derivatives.

Native consumers own pair traversal, effective ionic charges and atom scatter.
The same graph supplies first derivatives and directional second derivatives;
neither native assembly nor the Hessian consumer maintains a Coulomb rule.
"""

from functools import cache

from generativeqc_compiler.common.array_execution import arrays as np
from generativeqc_compiler.common.array_graph import evaluate_array_graph
from generativeqc_compiler.integral.expr import Expr, Graph
from generativeqc_compiler.integral.scalar_c import ScalarCEmitter


@cache
def nuclear_pair_program() -> tuple:
    """Return energy, three displacement gradients and three directional tangents.

    Coordinates and tangents are first-minus-second atom differences in atomic
    units. Native, array and Hessian AOT consumers share this ordered layout.
    """
    graph = Graph()
    displacement = tuple(graph.variable(f"r{axis}") for axis in range(3))
    energy = graph.variable("charge_product") * graph.sum(
        value * value for value in displacement
    ).pow(-0.5)
    gradient = tuple(graph.differentiate(energy, value) for value in displacement)
    tangent = {f"r{axis}": graph.variable(f"dr{axis}") for axis in range(3)}
    response = tuple(
        graph.differentiate(value, graph.variable("direction"), tangent)
        for value in gradient
    )
    return graph, (energy, *gradient, *response)


def nuclear_repulsion_hvp(
    centers: np.ndarray, charges: np.ndarray, direction: np.ndarray
) -> np.ndarray:
    """Apply generated pair Hessians with equal-and-opposite physical scatter."""
    first, second = np.triu_indices(len(centers), 1)
    result = np.zeros_like(centers)
    if not len(first):
        return result
    delta = centers[first] - centers[second]
    moving = direction[first] - direction[second]
    distances = np.linalg.norm(delta, axis=1)
    if np.any(~np.isfinite(distances)) or np.any(distances <= 0):
        raise ValueError("nuclear Hessian requires distinct finite centers")
    graph, roots = nuclear_pair_program()
    variables = {
        "charge_product": charges[first] * charges[second],
        **{f"r{axis}": delta[:, axis] for axis in range(3)},
        **{f"dr{axis}": moving[:, axis] for axis in range(3)},
    }
    values = np.asarray(evaluate_array_graph(graph, roots[4:], variables)).T
    np.add.at(result, first, values)
    np.add.at(result, second, -values)
    return result


def emit_nuclear_repulsion_header() -> str:
    """Emit deterministic, allocation-free C++ and CUDA scalar entry points."""
    graph, roots = nuclear_pair_program()
    lines = [
        "// Generated by tools/generate_nuclear_repulsion.py; do not edit.",
        "#pragma once",
        "#include <cmath>",
        "#if defined(__CUDACC__)",
        "#define GENERATIVEQC_NUCLEAR_HD __host__ __device__",
        "#else",
        "#define GENERATIVEQC_NUCLEAR_HD",
        "#endif",
        "namespace generativeqc::generated::nuclear_repulsion {",
    ]
    for name, requested_roots in (("energy", roots[:1]), ("gradient", roots[1:4])):
        selected = graph.replace_subexpressions(
            requested_roots,
            {
                Expr(graph, identifier): (
                    1 / Expr(graph, graph.nodes[identifier].arguments[0]).pow(0.5)
                ).pow(-2 * float(graph.nodes[identifier].payload))
                for identifier in graph.topological_order(requested_roots)
                if graph.nodes[identifier].operation == "power"
                and graph.nodes[identifier].payload in (-0.5, -1.5, -2.5)
            },
        )
        emission_graph, selected = graph.lower_small_integer_powers(
            selected, maximum_absolute_power=8
        )
        emission_graph, selected = emission_graph.canonicalize_associative(
            selected, factor_common=True
        )
        emitter = ScalarCEmitter(
            emission_graph,
            {
                "charge_product": "charge_product",
                **{f"r{axis}": f"r{axis}" for axis in range(3)},
            },
        )
        emitter.emit(selected)
        result_type = "double" if name == "energy" else "void"
        output = "" if name == "energy" else ", double* output"
        lines.extend(
            [
                f"GENERATIVEQC_NUCLEAR_HD inline {result_type} {name}(double charge_product,",
                f"    double r0, double r1, double r2{output}) {{",
                *emitter.lines,
            ]
        )
        if name == "energy":
            lines.append(f"  return {emitter.reference(selected[0])};")
        else:
            lines.extend(
                f"  output[{axis}] = {emitter.reference(root)};"
                for axis, root in enumerate(selected)
            )
        lines.append("}")
    lines.extend(["}", "#undef GENERATIVEQC_NUCLEAR_HD", ""])
    return "\n".join(lines)
