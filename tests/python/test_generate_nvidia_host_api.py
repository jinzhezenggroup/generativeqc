"""Provider-free host API code generation and fail-fast coverage without a GPU."""

from __future__ import annotations

import shutil
from pathlib import Path

import pytest

from tools import generate_nvidia_host_api as codegen

ROOT = Path(__file__).resolve().parents[2]


def test_checked_in_generated_host_api_covers_actual_calls() -> None:
    content = codegen.GENERATED.read_text()
    assert "Generated by tools/generate_nvidia_host_api.py" in content
    assert "cublasDgemmBatched(" in content
    assert "#define cublasDgemm cublasDgemm_v2" in content
    codegen.check_usage(ROOT, codegen.GENERATED)


def test_missing_api_fails_before_wheel_build(tmp_path: Path) -> None:
    path = tmp_path / "src/tensor/calls.cu"
    path.parent.mkdir(parents=True)
    path.write_text("void run() { cublasNewThing(); }\n")
    declared = tmp_path / "shim.h"
    declared.write_text(
        "#pragma once\n"
        "cublasStatus_t cublasDgemm_v2(cublasHandle_t arg0);\n"
        "#define cublasDgemm cublasDgemm_v2\n"
    )
    with pytest.raises(ValueError, match="cublasNewThing"):
        codegen.check_usage(tmp_path, declared)


def test_ast_stream_parser_and_pointer_signature() -> None:
    objects = codegen.ast_objects(
        '{"kind":"FunctionDecl","name":"cublasOne"}\n'
        '{"kind":"FunctionDecl","name":"cublasTwo"}\n'
    )
    assert [node["name"] for node in objects] == ["cublasOne", "cublasTwo"]
    assert codegen.canonical_type("const double * const *") == "const double*const*"
    output = codegen.render(
        {
            "cublasDgemmBatched": (
                "cublasStatus_t",
                "cublasHandle_t",
                "const double *const *",
                "double *const *",
            )
        },
        {"cublasDgemm": "cublasDgemm_v2"},
    )
    assert "const double*const* arg1, double*const* arg2" in output


def test_sdk_regeneration_is_deterministic_with_real_clang(tmp_path: Path) -> None:
    compiler = shutil.which("clang++")
    if compiler is None:
        pytest.skip("SDK parsing requires Clang, but the wheel build does not")

    sdk = tmp_path / "sdk"
    sdk.mkdir()
    (sdk / "cublas_v2.h").write_text(
        "#pragma once\n"
        "struct cublasContext;\n"
        "typedef cublasContext* cublasHandle_t;\n"
        "typedef int cublasStatus_t;\n"
        "enum cublasOperation_t { CUBLAS_OP_N=0, CUBLAS_OP_T=1 };\n"
        "cublasStatus_t cublasDgemmBatched(cublasHandle_t, cublasOperation_t, "
        "cublasOperation_t, int, int, int, const double*, const double*const*, "
        "int, const double*const*, int, const double*, double*const*, int, int);\n"
        "cublasStatus_t cublasDgemm_v2(cublasHandle_t);\n"
        "#define cublasDgemm cublasDgemm_v2\n"
    )
    (sdk / "cusolverDn.h").write_text(
        "#pragma once\n"
        "typedef int cusolverStatus_t;\n"
        "struct cusolverDnContext;\n"
        "typedef cusolverDnContext* cusolverDnHandle_t;\n"
        "cusolverStatus_t cusolverDnCreate(cusolverDnHandle_t*);\n"
    )

    owner = tmp_path / "src/tensor/consumer.cu"
    owner.parent.mkdir(parents=True)
    owner.write_text(
        "void use() { cublasDgemmBatched(); cublasDgemm(); cusolverDnCreate(); }\n"
    )
    existing = tmp_path / "generated.h"
    existing.write_text(
        "cublasStatus_t cublasDgemm_v2(cublasHandle_t arg0);\n"
        "#define cublasDgemm cublasDgemm_v2\n"
    )
    first = codegen.generate(tmp_path, existing, compiler, [sdk])
    assert "cublasDgemmBatched(" in first
    assert "const double*const* arg7" in first
    assert "#define cublasDgemm cublasDgemm_v2" in first
    assert "cusolverDnCreate(" in first
    existing.write_text(first)
    assert codegen.generate(tmp_path, existing, compiler, [sdk]) == first
    codegen.check_usage(tmp_path, existing)


@pytest.mark.parametrize(
    "declaration",
    [
        "/* cublasStatus_t cublasNewThing(void); */",
        "// cublasStatus_t cublasNewThing(void);",
        'const char* example = "cublasStatus_t cublasNewThing(void);";',
        (
            "cublasStatus_t cublasNewThing_v2(void);\n"
            "/*\n#define cublasNewThing cublasNewThing_v2\n*/"
        ),
        "#if 0\ncublasStatus_t cublasNewThing(void);\n#endif",
    ],
)
def test_inactive_declarations_fail_closed(tmp_path: Path, declaration: str) -> None:
    consumer = tmp_path / "src/consumer.cu"
    consumer.parent.mkdir()
    consumer.write_text("void f() { cublasNewThing(); }\n")
    header = tmp_path / "functions.h"
    header.write_text(declaration)
    with pytest.raises(ValueError, match="cublasNewThing|unconditional"):
        codegen.check_usage(tmp_path, header)


@pytest.mark.parametrize("separator", ["/**/", " /* why */ ", " // why\n "])
def test_comments_cannot_hide_missing_call(tmp_path: Path, separator: str) -> None:
    consumer = tmp_path / "src/consumer.cu"
    consumer.parent.mkdir()
    consumer.write_text(f"void f() {{ cublasNewThing{separator}(); }}\n")
    header = tmp_path / "functions.h"
    header.write_text("")
    with pytest.raises(ValueError, match="cublasNewThing"):
        codegen.check_usage(tmp_path, header)
    header.write_text("cublasStatus_t cublasNewThing(void);")
    codegen.check_usage(tmp_path, header)


@pytest.mark.parametrize(
    ("signature", "extra", "message"),
    [
        ("cublasStatus_t (int, ...)", {"variadic": True}, "variadic"),
        ("cublasStatus_t (int, ...)", {}, "variadic"),
        ("cublasStatus_t (int) __attribute__((ms_abi))", {}, "calling convention"),
    ],
)
def test_sdk_rejects_unrepresentable_function_abi(
    monkeypatch: pytest.MonkeyPatch,
    signature: str,
    extra: dict[str, bool],
    message: str,
) -> None:
    import json

    node = {
        "kind": "FunctionDecl",
        "name": "cublasNewThing",
        "type": {"qualType": signature},
        "inner": [{"kind": "ParmVarDecl", "type": {"qualType": "int"}}],
        **extra,
    }
    monkeypatch.setattr(codegen, "run_clang", lambda *args, **kwargs: json.dumps(node))
    with pytest.raises(ValueError, match=message):
        codegen.sdk_functions("clang++", [], "cublas_v2.h")


@pytest.mark.parametrize("kind", ["line", "block", "closed_blocks", "api_candidates"])
def test_comment_scanning_does_not_backtrack(kind: str) -> None:
    """Keep pathological comment runs bounded even when no call follows."""
    import subprocess
    import sys

    # Isolate the regression so a return to the old exponential expression
    # cannot hang a whole CI worker. It exceeded two seconds at 20 repeats.
    code = r"""
import sys
from tools.generate_nvidia_host_api import called_apis
kind = sys.argv[1]
comments = {
    "line": "//" * 20000 + "\n;",
    "block": "/*" + "*//*" * 20000 + ";",
    "closed_blocks": "/**/" * 20000 + ";",
    "api_candidates": "cublasNoise /* " * 20000,
}[kind]
assert called_apis("cublasMissing " + comments) == set()
assert called_apis("cublasPresent " + "/**/" * 20000 + "()") == {"cublasPresent"}
assert called_apis("cublasFirst/**/(); cusolverDnSecond // why\n (); cublasLast();") == {
    "cublasFirst", "cusolverDnSecond", "cublasLast"
}
"""
    subprocess.run(
        [sys.executable, "-c", code, kind],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
        timeout=10,
    )


